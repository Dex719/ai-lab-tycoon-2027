// У каждого варианта есть story - последствие словами, hint - то же числами.

import { addModifier, FOREVER } from '../sim/events';
import type { GameState, SegmentId } from '../sim/types';
import type { EventDef } from './events';
import { addHype, addRep, fixUnit, pay, roll, usd, windowFrom } from './eventKit';

/** Ничего не меняется: последствие словами своё у каждого письма. */
const nothing = (story: string) => ({ hint: 'без изменений', story, apply: () => {} });

/** Скидка на исследования на несколько дней (общая, без привязки к технологии). */
function researchDiscount(id: string, mult: number, days: number, s: GameState): void {
  addModifier(s, { id, kind: 'researchCost', mult, untilDay: s.day + days });
}

/** Доверие одного вида клиентов к лаборатории (бренд игрока в сегменте); days = null - до конца игры. */
function trust(s: GameState, id: string, seg: SegmentId, add: number, days: number | null): void {
  addModifier(s, { id, kind: 'segBrand', target: `player:${seg}`, add, untilDay: days === null ? FOREVER : s.day + days });
}

/** Откат идущих проектов обучения: часть расчётов придётся повторить. */
function rollback(s: GameState, share: number): void {
  for (const run of s.trainings) run.flopDone *= 1 - share;
}

/** Дата каждого исторического письма: раньше неё письмо не придёт (проверяют тесты). */
export const HISTORY_DATE: Record<string, string> = {};

function hist(date: string, def: Omit<EventDef, 'when'>): EventDef {
  HISTORY_DATE[def.id] = date;
  return { ...def, when: windowFrom(date) };
}

