// Сработать письмо может только в своём окне: сохранение, загруженное позже, не получит разом все старые заказы.

import type { EventDef } from './events';
import { addRep, grant, hasReleased, order, pay, REFUSE_HINT, refuseFocus, roll, usd, windowFrom } from './eventKit';

/** Отказ: исследования дешевле на 5 % на 30 дней; последствие словами своё у каждого письма. */
const decline = (story: string) => ({ label: 'Отказаться', hint: REFUSE_HINT, story, apply: refuseFocus });

/** Обычный заказ: взять за фиксированную плату или попросить больше (шанс не угадать). */
function orderEvent(opts: {
  id: string;
  date: string;
  title: string;
  body: string;
  pay: number;
  rep?: number;
  ask?: number; // сколько запросить, если торговаться
  askChance?: number;
  /** Последствия словами: взять заказ, отказаться. */
  takeStory: string;
  declineStory: string;
}): EventDef {
  const rep = opts.rep ?? 0;
  const choices: NonNullable<EventDef['choices']> = [
    {
      label: 'Взять заказ',
      story: opts.takeStory,
      hint: rep ? `+${usd(opts.pay)}, +${rep} репутации` : `+${usd(opts.pay)}`,
      apply: (s) => {
        order(s, opts.pay);
        if (rep) addRep(s, rep);
      },
    },
  ];
  if (opts.ask) {
    const p = opts.askChance ?? 0.5;
    choices.push({
      label: 'Попросить цену выше',
      story: 'Клиент может согласиться, а может найти исполнителя дешевле',
      hint: `+${usd(opts.ask)} с шансом ${Math.round(p * 100)} %, иначе клиент уйдёт к другим`,
      luck: { good: 'клиент согласился на цену выше', bad: 'клиент ушёл к другим' },
      apply: (s) => {
        if (roll(s, p, true)) order(s, opts.ask!);
      },
    });
  }
  choices.push(decline(opts.declineStory));
  return {
    id: opts.id,
    when: windowFrom(opts.date),
    mail: () => ({ kind: 'event', title: opts.title, body: opts.body }),
    choices,
  };
}

/** Конкурс: взнос сразу, приз получает тот, у кого уже есть выпущенная модель. */
function contestEvent(opts: { id: string; date: string; title: string; body: string; fee: number; prize: number; rep: number }): EventDef {
  return {
    id: opts.id,
    when: windowFrom(opts.date),
    mail: () => ({ kind: 'event', title: opts.title, body: opts.body }),
    choices: [
      {
        label: 'Участвовать в конкурсе',
        story: 'Выпущенную модель проверят на открытом наборе, без модели взнос пропадёт',
        hint: `-${usd(opts.fee)} взнос, +${usd(opts.prize)} и +${opts.rep} репутации, если есть выпущенная модель`,
        apply: (s) => {
          pay(s, opts.fee);
          if (hasReleased(s)) {
            grant(s, opts.prize);
            addRep(s, opts.rep);
          }
        },
      },
      decline('Конкурс пройдёт без лаборатории'),
    ],
  };
}

